import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const html = readFileSync(new URL("../main/editor.html", import.meta.url), "utf8");

test("Studio exposes provider-neutral generation, cancellation, and ZIP import controls", () => {
  for (const id of ["genUrl", "genToken", "genSource", "genStart", "genCancel", "genBundle", "genStatus"])
    assert.match(html, new RegExp(`id=["']${id}["']`));
  assert.match(html, /new GenerationClient\(endpoint,globalThis\.fetch,\$\("genToken"\)\.value\.trim\(\)\|\|null\)/);
  assert.match(html, /cancelJob\(running\.jobId\)/);
});

test("Studio rejects raw oversized ZIP inputs before JSZip inflation", () => {
  assert.match(html, /MAX_NVA_ZIP_BYTES=100\*1024\*1024/);
  assert.match(html, /assertRawZipBytes\(f\); const zip=await JSZip\.loadAsync\(f\)/);
  assert.match(html, /assertRawZipBytes\(bundle\); const zip=await JSZip\.loadAsync\(bundle\)/);
});

test("Studio verifies generated bytes and exports speech bundle paths", () => {
  assert.match(html, /blob\.size!==asset\.bytes/);
  assert.match(html, /sha256Hex\(blob\)!==asset\.sha256/);
  assert.match(html, /speechBundlePaths\(M\.speech_motion\)/);
  assert.match(html, /missing bundle asset/);
});
