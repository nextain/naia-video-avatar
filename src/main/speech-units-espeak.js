function utf16Offsets(chars) {
  const offsets = [0];
  for (const char of chars) offsets.push(offsets[offsets.length - 1] + char.length);
  return offsets;
}

function tokenizeIpa(value, word) {
  const units = [];
  let cursor = 0;
  while (cursor < value.length) {
    const match = SORTED_TOKEN_UNIT_PAIRS.find(([token]) => value.startsWith(token, cursor));
    if (match === undefined) return null;
    const [token] = match;
    units.push(normalizeAndMapPhone(token, word));
    cursor += token.length;
  }
  return units;
}

/** _map_ipa_phone: frozen 13-unit table, unmapped phones rejected. */
export function mapIpaPhone(rawPhone, word) {
  if (pythonStrip(rawPhone) === "spn") normalizeAndMapPhone(rawPhone, word);
  let cleaned = "";
  for (const char of rawPhone.normalize("NFD")) {
    if (!isCombining(char) && !REMOVE_TOKENS.has(char) && !REMOVE_MODIFIERS.has(char)) cleaned += char;
  }
  if (!cleaned) return [];
  const units = tokenizeIpa(cleaned, word);
  if (units !== null) return units;
  throw new SpeechUnitsError(
    "alignment_failed",
    `Unknown eSpeak phone '${rawPhone}' for word '${word}'; cannot map to the frozen 13-unit inventory`,
  );
}

/** _read_espeak_events after the engine call: [type, position, length, phone] -> word events. */
export function groupEspeakEvents(rawEvents, textLength) {
  if (!Array.isArray(rawEvents)) throw new SpeechUnitsError("alignment_failed", "eSpeak NG event data must be a list");
  const wordEvents = [];
  const prefixPhones = [];
  let current = null;
  for (const event of rawEvents) {
    if (!Array.isArray(event) || event.length !== 4) {
      throw new SpeechUnitsError("alignment_failed", "eSpeak NG returned a malformed event");
    }
    const [eventType, position, length, phone] = event;
    if (eventType === ESPEAK_EVENT_WORD) {
      if (current !== null && current.phones.length === 0) {
        throw new SpeechUnitsError(
          "alignment_failed",
          `eSpeak NG word at character ${current.textPosition} has no phonemes`,
        );
      }
      current = { textPosition: position, length, phones: [] };
      if (wordEvents.length === 0 && prefixPhones.length > 0) {
        if (position > 1) {
          wordEvents.push({ textPosition: 1, length: position - 1, phones: [...prefixPhones] });
        } else {
          current.phones.push(...prefixPhones);
        }
        prefixPhones.length = 0;
      }
      wordEvents.push(current);
    } else if (eventType === ESPEAK_EVENT_PHONEME && phone) {
      if (current === null) {
        if (position !== 0) {
          throw new SpeechUnitsError("alignment_failed", "eSpeak NG returned phonemes before its first word boundary");
        }
        prefixPhones.push(phone);
      } else {
        current.phones.push(phone);
      }
    }
  }
  if (prefixPhones.length > 0 && wordEvents.length === 0) {
    wordEvents.push({ textPosition: 1, length: textLength, phones: [...prefixPhones] });
  }
  if (wordEvents.length === 0 || wordEvents.some((event) => event.phones.length === 0)) {
    throw new SpeechUnitsError("alignment_failed", "eSpeak NG produced no complete word phoneme events");
  }
  return wordEvents;
}

/** _map_word_events: pair eSpeak source offsets with phone groups; merge overlapping expansions. */
export function mapWordEvents(text, events, { requireSourceCoverage = true } = {}) {
  const chars = Array.from(text); // eSpeak positions count characters (code points), like Python str.
  const codepointWords = [];
  for (const event of events) {
    const start = event.textPosition - 1; // eSpeak word positions are one-based source characters.
    const end = start + event.length;
    if (start < 0 || event.length <= 0 || end > chars.length) {
      throw new SpeechUnitsError(
        "alignment_failed",
        `eSpeak NG returned an invalid source word span (${event.textPosition}, ${event.length})`,
      );
    }
    const word = chars.slice(start, end).join("");
    const phones = [];
    for (const rawPhone of event.phones) phones.push(...mapIpaPhone(rawPhone, word));
    if (phones.length === 0) {
      throw new SpeechUnitsError("alignment_failed", `eSpeak NG produced no units for '${word}'`);
    }
    const previous = codepointWords[codepointWords.length - 1];
    if (previous && start < previous[1]) {
      if (start < previous[0]) throw new SpeechUnitsError("alignment_failed", "eSpeak NG word events are out of source order");
      codepointWords[codepointWords.length - 1] = [previous[0], Math.max(previous[1], end), [...previous[2], ...phones]];
    } else {
      if (previous && start < previous[0]) {
        throw new SpeechUnitsError("alignment_failed", "eSpeak NG word events are out of source order");
      }
      codepointWords.push([start, end, phones]);
    }
  }

  const result = [];
  const coverageSpans = [];
  const offsets = utf16Offsets(chars);
  codepointWords.forEach(([start, eventEnd, phones], index) => {
    let end = index + 1 < codepointWords.length ? codepointWords[index + 1][0] : eventEnd;
    while (end > start && isPythonSpace(chars[end - 1])) end--;
    if (end <= start) throw new SpeechUnitsError("alignment_failed", "eSpeak NG word group has an empty source span");
    coverageSpans.push([start, end]);
    result.push({ char_start: offsets[start], char_end: offsets[end], units: phones });
  });

  if (requireSourceCoverage) {
    const covered = new Array(chars.length).fill(false);
    for (const [start, end] of coverageSpans) for (let index = start; index < end; index++) covered[index] = true;
    chars.forEach((char, index) => {
      if (!isPythonSpace(char) && !isPunctuationSeparatorOrOther(char) && !covered[index]) {
        throw new SpeechUnitsError(
          "alignment_failed",
          `eSpeak NG did not return a word event covering source character ${index}: '${char}'`,
        );
      }
    });
  }
  return result;
}

/**
 * generate_speech_plan_units after the engine call. `ipa` is eSpeak's IPA phoneme trace
 * (`--ipa --sep=_`), `events` the WORD/PHONEME events as [type, text_position, length, phone].
 * Returns [{char_start, char_end, units}] with UTF-16 offsets into `text`.
 */
export function speechUnitsFromEspeakOutput(text, language, { ipa, events }) {
  if (typeof text !== "string" || !pythonStrip(text)) {
    throw new SpeechUnitsError("alignment_failed", "Input text cannot be empty");
  }
  if (!Object.hasOwn(ESPEAK_VOICES, language)) {
    throw new SpeechUnitsError("unsupported_language", `Unsupported eSpeak language: '${language}'`);
  }
  const marker = typeof ipa === "string" ? LANGUAGE_SWITCH_MARKER.exec(ipa) : null;
  if (marker) {
    throw new SpeechUnitsError(
      "alignment_failed",
      `eSpeak NG returned a language-switch marker '${marker[0]}'; speech plan rejected`,
    );
  }
  const chars = Array.from(text);
  const wordEvents = groupEspeakEvents(events, chars.length);
  const boundaryless = BOUNDARYLESS_LANGUAGES.has(language);
  const words = mapWordEvents(text, wordEvents, { requireSourceCoverage: !boundaryless });
  if (boundaryless) {
    return [{ char_start: 0, char_end: text.length, units: words.flatMap((word) => word.units) }];
  }
  return words;
}

// --- eSpeak NG engine (loaded on first use) ----------------------------------------------------

async function sha256Hex(bytes, digest) {
  if (digest) return digest(bytes);
  const hash = await globalThis.crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(hash), (byte) => byte.toString(16).padStart(2, "0")).join("");
}

async function verifiedBytes(name, bytes, digest) {
  const expected = ESPEAK_NG_ENGINE.files[name];
  const buffer = bytes instanceof ArrayBuffer ? bytes : bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
  const actual = await sha256Hex(buffer, digest);
  if (buffer.byteLength !== expected.size || actual !== expected.sha256) {
    throw new SpeechUnitsError(
      "engine_mismatch",
      `${name} is not the pinned eSpeak NG engine (${ESPEAK_NG_ENGINE.package} ${ESPEAK_NG_ENGINE.package_version})`,
    );
  }
  return buffer;
}

async function importFromBytes(buffer) {
  const url = URL.createObjectURL(new Blob([buffer], { type: "text/javascript" }));
  try {
    return await import(/* webpackIgnore: true */ /* turbopackIgnore: true */ /* @vite-ignore */ url);
  } finally {
    URL.revokeObjectURL(url);
  }
}

/**
 * Loads the pinned eSpeak NG engine. Both files are checked against ESPEAK_NG_ENGINE before use.
 * options.baseUrl: URL of the folder holding espeak-ng.js and espeak-ng.data (browser).
 * options.readFile(name) -> ArrayBuffer|Uint8Array overrides fetching (Node tests).
 * options.importModule(buffer, name) -> module overrides the blob import (Node tests).
 */
export async function loadEspeakNgEngine(options = {}) {
  const fetchImpl = options.fetchImpl ?? globalThis.fetch;
  const readFile = options.readFile ?? (async (name) => {
    const response = await fetchImpl(new URL(name, options.baseUrl).href);
    if (!response.ok) throw new SpeechUnitsError("engine_unavailable", `${name} could not be loaded (${response.status})`);
    return response.arrayBuffer();
  });
  const [script, data] = await Promise.all([
    readFile("espeak-ng.js").then((bytes) => verifiedBytes("espeak-ng.js", bytes, options.digest)),
    readFile("espeak-ng.data").then((bytes) => verifiedBytes("espeak-ng.data", bytes, options.digest)),
  ]);
  const module = await (options.importModule ?? importFromBytes)(script, "espeak-ng.js");
  return {
    engine: ESPEAK_NG_ENGINE,
    /**
     * A fresh engine instance per call, like the gateway's fresh process per request: eSpeak NG keeps
     * static state between syntheses (the phoneme events before the first word event of a later call
     * carry the previous call's text position), so one instance must not serve two texts.
     */
    async synthesize(text, voice) {
      const instance = await module.default({ getPreloadedPackage: () => data });
      const worker = new instance.eSpeakNGWorker();
      try {
        if (worker.set_voice(voice, voice) !== 0) {
          throw new SpeechUnitsError("alignment_failed", `eSpeak NG voice '${voice}' is unavailable`);
        }
        const events = [];
        const ipa = worker.synthesize_and_get_phonemes(text, (_samples, list) => {
          for (const event of list) {
            if (event.type === "word") events.push([ESPEAK_EVENT_WORD, event.text_position, event.word_length, null]);
            else if (event.type === "phoneme") events.push([ESPEAK_EVENT_PHONEME, event.text_position, 0, event.id]);
          }
          return false;
        });
        return { ipa, events };
      } finally {
        worker.__destroy__?.();
      }
    },
  };
}

/** Text -> speech-unit words with a loaded engine (generate_speech_plan_units). */
export async function textToSpeechUnits(engine, text, language) {
  if (typeof text !== "string" || !pythonStrip(text)) {
    throw new SpeechUnitsError("alignment_failed", "Input text cannot be empty");
  }
  const voice = ESPEAK_VOICES[language];
  if (!Object.hasOwn(ESPEAK_VOICES, language)) {
    throw new SpeechUnitsError("unsupported_language", `Unsupported eSpeak language: '${language}'`);
  }
  return speechUnitsFromEspeakOutput(text, language, await engine.synthesize(text, voice));
}

/**
 * Returns `speechUnits(text, language)` that loads the engine on its first call only and keeps it.
 * A failed load is not cached, so a later call may try again.
 */
export function createEspeakSpeechUnits(options = {}) {
  let loading = null;
  return async function speechUnits(text, language) {
    if (!Object.hasOwn(ESPEAK_VOICES, language)) {
      throw new SpeechUnitsError("unsupported_language", `Unsupported eSpeak language: '${language}'`);
    }
    loading ??= loadEspeakNgEngine(options).catch((error) => {
      loading = null;
      throw error;
    });
    const engine = await loading;
    return await textToSpeechUnits(engine, text, language);
  };
}

