export const REMOVE_TOKENS = Object.freeze(new Set([
  "ˈ", "ˌ", "ː", "ˑ", ".", "‿", "-", "1", "2", "3", "4", "5", "6", "7", "˥", "˦", "˧", "˨", "˩",
]));
export const REMOVE_MODIFIERS = Object.freeze(new Set(["ʰ", "ʲ", "ʷ", "ˠ", "ˤ", "ᵝ"]));

function inRanges(ranges, codePoint) {
  let low = 0;
  let high = ranges.length / 2 - 1;
  while (low <= high) {
    const mid = (low + high) >> 1;
    if (codePoint < ranges[mid * 2]) high = mid - 1;
    else if (codePoint > ranges[mid * 2 + 1]) low = mid + 1;
    else return true;
  }
  return false;
}

/** Python unicodedata.combining(char) != 0 */
export function isCombining(char) {
  return inRanges(COMBINING_RANGES, char.codePointAt(0));
}

/** Python str.isspace() for one character */
export function isPythonSpace(char) {
  return inRanges(PYTHON_SPACE_RANGES, char.codePointAt(0));
}

/** Python unicodedata.category(char)[0] in {"P", "Z", "C"} */
function isPunctuationSeparatorOrOther(char) {
  return inRanges(PZC_CATEGORY_RANGES, char.codePointAt(0));
}

/** Python str.strip() (whitespace only) */
function pythonStrip(value) {
  const chars = Array.from(value);
  let start = 0;
  let end = chars.length;
  while (start < end && isPythonSpace(chars[start])) start++;
  while (end > start && isPythonSpace(chars[end - 1])) end--;
  return chars.slice(start, end).join("");
}

function stripCombining(value) {
  let out = "";
  for (const char of value.normalize("NFD")) if (!isCombining(char)) out += char;
  return out;
}

// SORTED_TOKEN_UNIT_PAIRS: tokens with combining marks removed, longest (in code points) first,
// stable for equal lengths — the same order Python's list.sort(reverse=True) keeps.
export const SORTED_TOKEN_UNIT_PAIRS = Object.freeze(
  Object.entries(PHONE_MAP)
    .flatMap(([unit, tokens]) => tokens.map((token) => [stripCombining(token), unit]))
    .map((pair, index) => ({ pair, index }))
    .sort((a, b) => Array.from(b.pair[0]).length - Array.from(a.pair[0]).length || a.index - b.index)
    .map(({ pair }) => Object.freeze(pair)),
);
const EXACT_TOKEN_TO_UNIT = new Map(SORTED_TOKEN_UNIT_PAIRS.map(([token, unit]) => [token, unit]));

/** normalize_and_map_phone(raw_phone, word) */
export function normalizeAndMapPhone(rawPhone, word) {
  let cleaned = "";
  for (const char of stripCombining(rawPhone)) {
    if (!REMOVE_TOKENS.has(char) && !REMOVE_MODIFIERS.has(char)) cleaned += char;
  }
  cleaned = pythonStrip(cleaned);
  const context = word !== undefined && word !== null ? ` (word='${word}')` : "";
  if (cleaned === "spn" || pythonStrip(rawPhone) === "spn") {
    throw new SpeechUnitsError(
      "alignment_failed",
      `OOV / unaligned phone 'spn'${context} cannot be mapped to 13-unit inventory`,
    );
  }
  if (!cleaned) return "sil";
  const unit = EXACT_TOKEN_TO_UNIT.get(cleaned);
  if (unit !== undefined) return unit;
  throw new SpeechUnitsError(
    "alignment_failed",
    `Unknown phone: '${rawPhone}' (normalized: '${cleaned}')${context} cannot be mapped to 13-unit inventory`,
  );
}

